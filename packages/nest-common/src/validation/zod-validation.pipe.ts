import { Injectable, type ArgumentMetadata, type PipeTransform } from '@nestjs/common';
import { z } from 'zod';

import { ProblemException } from '../problem/problem.js';

/**
 * Interface ZodDto
 *
 * @description
 * Class produced by `zodDto`: its instances have the parsed type of the schema, and the schema
 * travels with the class so the global validation pipe finds it.
 */
export interface ZodDto<TValue> {
  // #region Properties
  /**
   * Property schema
   *
   * @description
   * Schema the pipe validates the parameter with.
   *
   * @type {z.ZodType<TValue>}
   * @readonly
   */
  readonly schema: z.ZodType<TValue>;
  // #endregion

  // #region Constructor
  /**
   * Constructor
   *
   * @description
   * Present only so the class can be used as a parameter type; never called.
   *
   * @constructor
   */
  new (): TValue;
  // #endregion
}

/**
 * Interface ValidationIssue
 *
 * @description
 * One entry of `details.issues` in a `request.invalid` problem.
 */
export interface ValidationIssue {
  // #region Properties
  /**
   * Property in
   *
   * @description
   * Part of the request the value came from.
   *
   * @type {'body' | 'query' | 'param' | 'custom'}
   * @readonly
   */
  readonly in: 'body' | 'query' | 'param' | 'custom';

  /**
   * Property path
   *
   * @description
   * Dotted path of the faulty member, empty for the value itself.
   *
   * @type {string}
   * @readonly
   */
  readonly path: string;

  /**
   * Property code
   *
   * @description
   * Zod issue code, `unrecognized_parameter` for an unknown query parameter, or `invalid_json`
   * for a request body that is not valid JSON.
   *
   * @type {string}
   * @readonly
   */
  readonly code: string;

  /**
   * Property message
   *
   * @description
   * Explanation of the issue. It names the expectation, never the received value.
   *
   * @type {string}
   * @readonly
   */
  readonly message: string;
  // #endregion
}

/**
 * Function zodDto
 *
 * @description
 * Wraps a zod schema, usually one generated by `@cadenway/contracts`, into a class usable as the
 * type of a controller parameter: `class ListTasksQuery extends zodDto(listTasksQuerySchema) {}`
 * then `@Query() query: ListTasksQuery`. The global `ZodValidationPipe` validates such a
 * parameter with the schema.
 *
 * @param {z.ZodType<TValue>} schema - Schema of the parameter.
 * @returns {ZodDto<TValue>} A class carrying the schema.
 */
export function zodDto<TValue>(schema: z.ZodType<TValue>): ZodDto<TValue> {
  const dto: { schema: z.ZodType<TValue> } = Object.assign(
    function ZodDtoBase(): void {
      // Never called: the function only exists to be extended and to carry the schema.
    },
    { schema },
  );
  return dto as unknown as ZodDto<TValue>;
}

/**
 * Function schemaOf
 *
 * @description
 * Finds the schema a parameter type carries.
 *
 * @param {unknown} metatype - Declared type of the controller parameter.
 * @returns {z.ZodType | undefined} The schema of a `zodDto` class, or `undefined`.
 */
function schemaOf(metatype: unknown): z.ZodType | undefined {
  if (typeof metatype !== 'function') {
    return undefined;
  }
  const schema: unknown = (metatype as { schema?: unknown }).schema;
  return schema instanceof z.ZodType ? schema : undefined;
}

/**
 * Function unknownParameters
 *
 * @description
 * Lists the query parameters an object schema does not declare. Zod drops unknown keys by
 * default, whereas the contract style answers 400 to an unknown parameter.
 *
 * @param {z.ZodType} schema - Schema of the query string.
 * @param {unknown} value - Parsed query string.
 * @returns {string[]} Names of the unknown parameters; empty when the schema is not an object schema.
 */
function unknownParameters(schema: z.ZodType, value: unknown): string[] {
  if (!(schema instanceof z.ZodObject) || typeof value !== 'object' || value === null) {
    return [];
  }
  const declared: Record<string, unknown> = schema.shape;
  return Object.keys(value).filter((name: string) => !Object.hasOwn(declared, name));
}

/**
 * Class ZodValidationPipe
 *
 * @description
 * Validates a controller parameter with a zod schema and hands the parsed value to the handler.
 *
 * Two uses:
 *
 * - per parameter, with a schema: `@Body(new ZodValidationPipe(schema)) body: CreateTask`;
 * - globally, without one: a parameter whose type is a `zodDto` class is validated with the
 *   schema of that class, and any other parameter passes through untouched.
 *
 * A failure answers 400 `request.invalid` with one `details.issues` entry per issue. For a query
 * string checked against an object schema, a parameter the schema does not declare is an issue
 * (`unrecognized_parameter`). Body and path values follow the schema as written.
 */
@Injectable()
export class ZodValidationPipe implements PipeTransform {
  // #region Constructor
  /**
   * Constructor
   *
   * @description
   * Stores the schema of a per-parameter pipe; none for the global pipe.
   *
   * @param {z.ZodType | undefined} schema - Schema to validate with.
   * @constructor
   */
  public constructor(private readonly schema?: z.ZodType) {}
  // #endregion

  // #region Methods
  /**
   * Method transform
   *
   * @description
   * Parses the value, or throws the validation problem.
   *
   * @param {unknown} value - Raw value of the parameter.
   * @param {ArgumentMetadata} metadata - Where the value comes from and its declared type.
   * @returns {unknown} The parsed value, or the raw value when no schema applies.
   * @throws {ProblemException} 400 `request.invalid` when the value does not satisfy the schema.
   */
  public transform(value: unknown, metadata: ArgumentMetadata): unknown {
    const schema: z.ZodType | undefined = this.schema ?? schemaOf(metadata.metatype);
    if (schema === undefined) {
      return value;
    }
    const issues: ValidationIssue[] = [];
    if (metadata.type === 'query') {
      for (const name of unknownParameters(schema, value)) {
        issues.push({
          in: 'query',
          path: name,
          code: 'unrecognized_parameter',
          message: 'Unknown query parameter.',
        });
      }
    }
    const result: z.ZodSafeParseResult<unknown> = schema.safeParse(value);
    if (!result.success) {
      for (const issue of result.error.issues) {
        issues.push({
          in: metadata.type,
          path: issue.path.join('.'),
          code: issue.code,
          message: issue.message,
        });
      }
    }
    if (issues.length > 0 || !result.success) {
      throw new ProblemException({
        status: 400,
        code: 'request.invalid',
        detail: 'The request does not match its contract.',
        details: { issues },
      });
    }
    return result.data;
  }
  // #endregion
}
