import { describe, expect, expectTypeOf, it } from 'vitest';
import * as zod from 'zod';

import * as identityService from '../testing/contracts/events/identity-service.js';
import * as taskService from '../testing/contracts/events/task-service.js';
import type { EventDataOf, EventPayloadOf, EventSchemas } from './event-envelope.js';

/**
 * Constant nextContracts
 *
 * @description
 * An event module as a later minor of `@cadenway/contracts` could generate it: the same shape as
 * the generated modules, with one more kind of actor.
 *
 * @type {{ readonly 'task.archived.v1': zod.ZodObject<{ id: zod.ZodUUID; occurredAt: zod.ZodISODateTime; organizationId: zod.ZodUUID; actor: zod.ZodObject<{ type: zod.ZodEnum<{ user: 'user'; automation: 'automation'; git: 'git'; system: 'system'; 'service-account': 'service-account' }>; id: zod.ZodString }>; version: zod.ZodInt }> }}
 */
const nextContracts: {
  readonly 'task.archived.v1': zod.ZodObject<{
    id: zod.ZodUUID;
    occurredAt: zod.ZodISODateTime;
    organizationId: zod.ZodUUID;
    actor: zod.ZodObject<{
      type: zod.ZodEnum<{
        user: 'user';
        automation: 'automation';
        git: 'git';
        system: 'system';
        'service-account': 'service-account';
      }>;
      id: zod.ZodString;
    }>;
    version: zod.ZodInt;
  }>;
} = {
  'task.archived.v1': zod.object({
    id: zod.uuid(),
    occurredAt: zod.iso.datetime(),
    organizationId: zod.uuid(),
    actor: zod.object({
      type: zod.enum(['user', 'automation', 'git', 'system', 'service-account']),
      id: zod.string(),
    }),
    version: zod.int(),
  }),
};

/**
 * Type TaskMovedV1
 *
 * @description
 * Payload of an event that is a discriminated union, as a contract with `oneOf` generates it.
 *
 * @type {{ id: string; occurredAt: string; organizationId: string; actor: { type: 'user'; id: string }; version: number } & ({ to: 'list'; listId: string } | { to: 'sprint'; sprintId: string })}
 */
type TaskMovedV1 = {
  id: string;
  occurredAt: string;
  organizationId: string;
  actor: { type: 'user'; id: string };
  version: number;
} & ({ to: 'list'; listId: string } | { to: 'sprint'; sprintId: string });

/**
 * Constant unionContracts
 *
 * @description
 * Event module with one union event.
 *
 * @type {{ readonly 'task.moved.v1': zod.ZodType<TaskMovedV1> }}
 */
const unionContracts: { readonly 'task.moved.v1': zod.ZodType<TaskMovedV1> } = {
  'task.moved.v1': zod.discriminatedUnion('to', [
    zod.object({
      id: zod.uuid(),
      occurredAt: zod.iso.datetime(),
      organizationId: zod.uuid(),
      actor: zod.object({ type: zod.literal('user'), id: zod.string() }),
      version: zod.int(),
      to: zod.literal('list'),
      listId: zod.string(),
    }),
    zod.object({
      id: zod.uuid(),
      occurredAt: zod.iso.datetime(),
      organizationId: zod.uuid(),
      actor: zod.object({ type: zod.literal('user'), id: zod.string() }),
      version: zod.int(),
      to: zod.literal('sprint'),
      sprintId: zod.string(),
    }),
  ]),
};

/**
 * Type MovedData
 *
 * @description
 * What a caller gives to publish the union event.
 *
 * @type {EventDataOf<typeof unionContracts, 'task.moved.v1'>}
 */
type MovedData = EventDataOf<typeof unionContracts, 'task.moved.v1'>;

describe('event envelope types', () => {
  it('accepts the eventSchemas objects generated by cadenway-api-contracts', () => {
    expectTypeOf(taskService.eventSchemas).toExtend<EventSchemas>();
    expectTypeOf(identityService.eventSchemas).toExtend<EventSchemas>();
    expectTypeOf<
      EventPayloadOf<typeof taskService.eventSchemas, 'task.updated.v1'>
    >().toEqualTypeOf<taskService.TaskUpdatedV1>();

    expect(Object.keys(taskService.eventSchemas)).toEqual([...taskService.EVENT_NAMES]);
  });

  it('still accepts a contract that adds a kind of actor the kit does not know', () => {
    expectTypeOf(nextContracts).toExtend<EventSchemas>();

    const schemas: EventSchemas = nextContracts;
    expect(Object.keys(schemas)).toEqual(['task.archived.v1']);
  });

  it('keeps the variants of a union payload when id and occurredAt are left out', () => {
    expectTypeOf(unionContracts).toExtend<EventSchemas>();

    expectTypeOf<Extract<MovedData, { to: 'list' }>>().toHaveProperty('listId');
    expectTypeOf<Extract<MovedData, { to: 'sprint' }>>().toHaveProperty('sprintId');
    expectTypeOf<MovedData>().not.toHaveProperty('id');
    expectTypeOf<MovedData>().not.toHaveProperty('occurredAt');

    const data: MovedData = {
      organizationId: '0193a1f0-0000-7000-8000-00000000000a',
      actor: { type: 'user', id: 'user-camille' },
      version: 2,
      to: 'sprint',
      sprintId: 'sprint-12',
    };
    expect(data.to).toBe('sprint');
  });
});
