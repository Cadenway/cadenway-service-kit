import { z } from 'zod';

import type { EventEnvelope } from '../events/event-envelope.js';

/**
 * Constant ATELIER_NORD
 *
 * @description
 * Id of the first organization of the fixtures.
 *
 * @type {string}
 */
export const ATELIER_NORD: string = '0193a1f0-0000-7000-8000-00000000000a';

/**
 * Constant OTHER_ORGANIZATION
 *
 * @description
 * Id of a second organization of the fixtures.
 *
 * @type {string}
 */
export const OTHER_ORGANIZATION: string = '0193a1f0-0000-7000-8000-00000000000b';

/**
 * Constant CAMILLE
 *
 * @description
 * Id of the user who causes the events of the fixtures.
 *
 * @type {string}
 */
export const CAMILLE: string = '0193a1f0-0000-7000-8000-0000000000c1';

/**
 * Interface TaskUpdatedV1
 *
 * @description
 * Payload of the fixture event `task.updated.v1`, shaped like a payload generated by
 * `@cadenway/contracts`: an event that belongs to an organization.
 */
export interface TaskUpdatedV1 extends EventEnvelope {
  // #region Properties
  /**
   * Property organizationId
   *
   * @description
   * Organization of the task.
   *
   * @type {string}
   * @readonly
   */
  readonly organizationId: string;

  /**
   * Property taskId
   *
   * @description
   * Id of the task that changed.
   *
   * @type {string}
   * @readonly
   */
  readonly taskId: string;

  /**
   * Property changed
   *
   * @description
   * Names of the fields that changed.
   *
   * @type {string[]}
   * @readonly
   */
  readonly changed: string[];
  // #endregion
}

/**
 * Interface UserSignedUpV1
 *
 * @description
 * Payload of the fixture event `user.signed-up.v1`: an event outside any organization.
 */
export interface UserSignedUpV1 extends EventEnvelope {
  // #region Properties
  /**
   * Property organizationId
   *
   * @description
   * Always `null`: an account exists before it joins an organization.
   *
   * @type {null}
   * @readonly
   */
  readonly organizationId: null;

  /**
   * Property userId
   *
   * @description
   * Id of the account created.
   *
   * @type {string}
   * @readonly
   */
  readonly userId: string;
  // #endregion
}

/**
 * Constant envelopeShape
 *
 * @description
 * Zod shape of the fields every event carries, except the organization.
 *
 * @type {{ id: z.ZodType<string>; occurredAt: z.ZodType<string>; actor: z.ZodType<EventEnvelope['actor']>; version: z.ZodType<number> }}
 */
const envelopeShape: {
  id: z.ZodType<string>;
  occurredAt: z.ZodType<string>;
  actor: z.ZodType<EventEnvelope['actor']>;
  version: z.ZodType<number>;
} = {
  id: z.uuid(),
  occurredAt: z.iso.datetime(),
  actor: z.object({
    type: z.enum(['user', 'automation', 'git', 'system']),
    id: z.string(),
  }),
  version: z.int().min(1),
};

/**
 * Constant TASK_UPDATED_V1
 *
 * @description
 * Name of the fixture event of an organization.
 *
 * @type {'task.updated.v1'}
 */
export const TASK_UPDATED_V1: 'task.updated.v1' = 'task.updated.v1';

/**
 * Constant USER_SIGNED_UP_V1
 *
 * @description
 * Name of the fixture event without an organization.
 *
 * @type {'user.signed-up.v1'}
 */
export const USER_SIGNED_UP_V1: 'user.signed-up.v1' = 'user.signed-up.v1';

/**
 * Constant eventSchemas
 *
 * @description
 * Fixture with the shape of the `eventSchemas` object of an event module of
 * `@cadenway/contracts`: the validator of each event, by event name.
 *
 * @type {{ readonly 'task.updated.v1': z.ZodType<TaskUpdatedV1>; readonly 'user.signed-up.v1': z.ZodType<UserSignedUpV1> }}
 */
export const eventSchemas: {
  readonly 'task.updated.v1': z.ZodType<TaskUpdatedV1>;
  readonly 'user.signed-up.v1': z.ZodType<UserSignedUpV1>;
} = {
  'task.updated.v1': z.object({
    ...envelopeShape,
    organizationId: z.uuid(),
    taskId: z.string().min(1),
    changed: z.array(z.string()),
  }),
  'user.signed-up.v1': z.object({
    ...envelopeShape,
    organizationId: z.null(),
    userId: z.uuid(),
  }),
};

/**
 * Function taskUpdated
 *
 * @description
 * Builds the data of a `task.updated.v1` event, as a use case gives it to the kit.
 *
 * @param {Partial<Omit<TaskUpdatedV1, 'id' | 'occurredAt'>>} overrides - Fields that differ from the default fixture.
 * @returns {Omit<TaskUpdatedV1, 'id' | 'occurredAt'>} The event data.
 */
export function taskUpdated(
  overrides: Partial<Omit<TaskUpdatedV1, 'id' | 'occurredAt'>> = {},
): Omit<TaskUpdatedV1, 'id' | 'occurredAt'> {
  return {
    organizationId: ATELIER_NORD,
    actor: { type: 'user', id: CAMILLE },
    version: 1,
    taskId: 'CAD-482',
    changed: ['status'],
    ...overrides,
  };
}

/**
 * Function userSignedUp
 *
 * @description
 * Builds the data of a `user.signed-up.v1` event.
 *
 * @returns {Omit<UserSignedUpV1, 'id' | 'occurredAt'>} The event data.
 */
export function userSignedUp(): Omit<UserSignedUpV1, 'id' | 'occurredAt'> {
  return {
    organizationId: null,
    actor: { type: 'user', id: CAMILLE },
    version: 1,
    userId: CAMILLE,
  };
}
