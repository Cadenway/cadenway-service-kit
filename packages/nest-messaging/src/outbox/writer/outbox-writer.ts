import type { DatabaseSchema, TransactionScope } from '@cadenway/nest-common/database';
import { Inject, Injectable } from '@nestjs/common';

import type {
  EventDataOf,
  EventNameOf,
  EventPayloadOf,
  EventSchemas,
} from '../../events/event-envelope.js';
import { validateEvent } from '../../events/event-validation.js';
import { eventRoute, type EventRoute } from '../../transport/event-route.js';
import {
  MESSAGING_OPTIONS,
  type ResolvedMessagingOptions,
} from '../../configuration/messaging-options.js';
import { currentTraceparent } from '../../observability/trace-context.js';

/**
 * Interface AppendedEvent
 *
 * @description
 * What PostgreSQL assigned to an event appended to the outbox.
 */
export interface AppendedEvent {
  // #region Properties
  /**
   * Property id
   *
   * @description
   * Id of the event, a UUID version 7 generated by PostgreSQL.
   *
   * @type {string}
   * @readonly
   */
  readonly id: string;

  /**
   * Property occurredAt
   *
   * @description
   * Instant of the event: the start of the transaction, as an ISO 8601 date-time in UTC.
   *
   * @type {string}
   * @readonly
   */
  readonly occurredAt: string;
  // #endregion
}

/**
 * Class OutboxWriter
 *
 * @description
 * Appends events to the outbox of a service, inside the transaction of the use case that causes
 * them. The event is published later by the relay, if and only if that transaction commits.
 */
@Injectable()
export class OutboxWriter {
  // #region Constructor
  /**
   * Constructor
   *
   * @description
   * Stores the options of the messaging module, which decide the route of an event.
   *
   * @param {ResolvedMessagingOptions} options - Options of `MessagingModule`.
   * @constructor
   */
  public constructor(
    @Inject(MESSAGING_OPTIONS) private readonly options: ResolvedMessagingOptions,
  ) {}
  // #endregion

  // #region Methods
  /**
   * Method append
   *
   * @description
   * Completes a payload with an id and an instant asked from PostgreSQL (`uuidv7()`, `now()`),
   * validates it with the schema of the event, routes it, captures the trace context of the
   * caller and inserts the pending row through the given transaction. The route (subject and
   * stream) is stored with the row: a restricted event stays restricted whatever the options of
   * the replica that relays it.
   *
   * An event that carries an organization is appended in a transaction of the tenant runner for
   * that organization, or in a system transaction. An event without an organization is appended
   * in a system transaction only: the row-level security policy of the table refuses it in a
   * tenant one, and so does this method, with a clearer error.
   *
   * @param {TransactionScope<TDatabase>} tx - Scope of the transaction of the use case, from the tenant or the system runner.
   * @param {TSchemas} schemas - `eventSchemas` object of an event module of `@cadenway/contracts`.
   * @param {TName} name - Name of the event.
   * @param {EventDataOf<TSchemas, TName>} data - Payload without `id` and `occurredAt`.
   * @returns {Promise<AppendedEvent>} The id and the instant PostgreSQL assigned.
   * @throws {EventValidationError} When the payload does not match its contract; nothing is written and the payload is not echoed.
   * @throws {Error} When a tenant transaction is given an event of another organization or of none.
   */
  public async append<
    TDatabase extends DatabaseSchema,
    TSchemas extends EventSchemas,
    TName extends EventNameOf<TSchemas>,
  >(
    tx: TransactionScope<TDatabase>,
    schemas: TSchemas,
    name: TName,
    data: EventDataOf<TSchemas, TName>,
  ): Promise<AppendedEvent> {
    // The instant is formatted by PostgreSQL so it does not depend on the type parsers of the
    // driver.
    const assigned: { rows: unknown[] } = await tx.client.query(
      `select uuidv7()::text as id,
              to_char(now() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') as occurred_at`,
    );
    const row: { id: string; occurred_at: string } = assigned.rows[0] as {
      id: string;
      occurred_at: string;
    };
    const payload: EventPayloadOf<TSchemas, TName> = validateEvent(schemas, name, {
      ...data,
      id: row.id,
      occurredAt: row.occurred_at,
    });
    const route: EventRoute = eventRoute(this.options, name);
    if (tx.kind === 'tenant' && payload.organizationId !== tx.organizationId) {
      throw new Error(
        `The event ${name} does not belong to the organization of this transaction: an event of another organization or without one is appended in a system transaction.`,
      );
    }
    await tx.client.query(
      `insert into outbox_events
         (id, event_name, subject, stream, organization_id, payload, traceparent)
       values ($1, $2, $3, $4, $5, $6::jsonb, $7)`,
      [
        payload.id,
        name,
        route.subject,
        route.stream,
        payload.organizationId,
        JSON.stringify(payload),
        currentTraceparent(),
      ],
    );
    return { id: payload.id, occurredAt: payload.occurredAt };
  }
  // #endregion
}
